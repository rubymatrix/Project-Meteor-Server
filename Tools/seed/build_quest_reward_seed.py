#!/usr/bin/env python3
"""Quest reward seed: client quest_new_reward sheet -> gamedata_quest_rewards.

Inputs (read only; regenerate with decomp/tools/xivsheet.py, gitignored, never commit them):
  * decomp/build/sheets/all/quest_new_reward.csv - 500 rows, id = quest id, 16 slots x 13 s32.
  * decomp/build/sheets/all/quest.csv            - col 51 = quest (recommended) level.

Slot layout ( 6.3; client QuestRewardWidget.setRewardData,
QuestBaseClass_common.sqrwa):
  w0  slot type: 100 completion reward (listed in sqrwa), 300 mid-quest payout (not shown at
      completion), 301 empty, 302 command unlock / optional
  w1  kind: -2 gil, -12/-13 EXP (client prints the sqrwa EXP argument), -16 EXP to skill w11,
      -10/-8/-3/-14 item w3 x amount, -15 company seals of the player's GC, -4 command w3
  w2  icon, w3 item / command id, w4 unknown (5000 on mid-quest gil), w5..w8 amount by tier
      (sqrwa tier argument; negative = use w5), w11 skill (for -16)

Output: Data/sql/seed/seed_quest_rewards.sql (drops and recreates gamedata_quest_rewards; empty 301
slots are left out). Read by Map Server/DataObjects/QuestReward.cs.
"""
import csv, os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
WORKSPACE = os.path.dirname(REPO)
SHEETS = os.path.join(WORKSPACE, 'decomp', 'build', 'sheets', 'all')
OUT = os.path.join(REPO, 'Data', 'sql', 'seed', 'seed_quest_rewards.sql')


def main():
    levels = {}
    with open(os.path.join(SHEETS, 'quest.csv')) as f:
        rows = csv.reader(f)
        hdr = next(rows)
        col51 = next(i for i, h in enumerate(hdr) if h.startswith('51:'))
        for r in rows:
            levels[int(r[0])] = int(r[col51] or 0)

    out = []
    with open(os.path.join(SHEETS, 'quest_new_reward.csv')) as f:
        rows = csv.reader(f)
        next(rows)
        for r in rows:
            qid = int(r[0])
            if qid < 110001:
                continue
            v = [int(x) for x in r[1:]]
            for s in range(16):
                w = v[s * 13:(s + 1) * 13]
                if len(w) < 13 or w[0] == 301:
                    continue
                out.append((qid, s + 1, w[0], w[1], w[2], w[3], w[4], w[5], w[6], w[7], w[8], w[11],
                            levels.get(qid, 0)))

    with open(OUT, 'w') as f:
        f.write('-- Generated by tools/seed/build_quest_reward_seed.py from the client quest_new_reward sheet.\n')
        f.write('-- Do not edit by hand; rerun the script.\n')
        f.write('DROP TABLE IF EXISTS `gamedata_quest_rewards`;\n')
        f.write('''CREATE TABLE `gamedata_quest_rewards` (
  `questId` int(11) unsigned NOT NULL,
  `slot` tinyint(3) unsigned NOT NULL,
  `slotType` smallint(6) NOT NULL,
  `kind` smallint(6) NOT NULL,
  `iconId` int(11) NOT NULL,
  `targetId` int(11) NOT NULL,
  `param` int(11) NOT NULL,
  `amount1` int(11) NOT NULL,
  `amount2` int(11) NOT NULL,
  `amount3` int(11) NOT NULL,
  `amount4` int(11) NOT NULL,
  `skill` int(11) NOT NULL,
  `questLevel` smallint(6) NOT NULL,
  PRIMARY KEY (`questId`, `slot`)
) ENGINE=InnoDB DEFAULT CHARSET=latin1;
''')
        cols = '(`questId`, `slot`, `slotType`, `kind`, `iconId`, `targetId`, `param`, `amount1`, `amount2`, `amount3`, `amount4`, `skill`, `questLevel`)'
        for i in range(0, len(out), 200):
            f.write('INSERT INTO `gamedata_quest_rewards` %s VALUES\n' % cols)
            f.write(',\n'.join('\t(%s)' % ', '.join(str(x) for x in row) for row in out[i:i + 200]))
            f.write(';\n')
    print('%d reward slots for %d quests -> %s' % (len(out), len({o[0] for o in out}), OUT))


if __name__ == '__main__':
    main()
