#!/usr/bin/env python3
"""Model size seed: each model's client `cibb` record -> gamedata_model_size.

Input (read only, never commit it): the retail install's chara/{pc,mon,bgobj}/<model>/skl/0001.
Each is a PWIB package; the row typed `bbic` is the model's 0x54-byte cibb record
(decomp/docs/actor_size.md §2):
  * +0x00 version. v1 size table at +0x44 (8 x s16, /1000), v0 table at +0x04.
  * +0x1c pick-sphere radius at the root, +0x25 body radius (both u8, x0.1, before scale).
  * +0x31 bit 0x80: flyer.

The client scales the model by table[SIZE] / 1000, SIZE being SetActorAppearance's size slot
(gamedata_actor_appearance.size), and the radii by that scale.

Model ids are the appearance `base` values: c<n> = n, mon m<n> = 10000 + n, bgobj b<n> = 20000 + n.

Output: Data/sql/seed/seed_model_size.sql (drops and recreates the table). Read by
Database.GetModelSizeGamedata.
"""
import argparse, os, struct

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
WORKSPACE = os.path.dirname(REPO)
INSTALL = os.path.join(WORKSPACE, 'installer', 'target', 'prefix', 'drive_c', 'Program Files (x86)',
                       'SquareEnix', 'FINAL FANTASY XIV')
OUT = os.path.join(REPO, 'Data', 'sql', 'seed', 'seed_model_size.sql')

KINDS = (('pc', 'c', 0), ('mon', 'm', 10000), ('bgobj', 'b', 20000))


def cibb(path):
    """The bbic row of a PWIB skeleton package, or None."""
    with open(path, 'rb') as f:
        b = f.read()
    if len(b) < 0x50:
        return None
    n = struct.unpack_from('<I', b, 0x40)[0]
    if n < 3 or 0x50 + 0x10 * n > len(b):
        return None
    base = 0x50 + 0x10 * n
    ents = [struct.unpack_from('<4I', b, 0x50 + 0x10 * i) for i in range(n)]
    rows = n - 2
    to = base + ents[rows][1]
    types = [b[to + 4 * i:to + 4 * i + 4] for i in range(rows)]
    if b'bbic' not in types:
        return None
    _, off, size, _ = ents[types.index(b'bbic')]
    rec = b[base + off:base + off + size]
    return rec if len(rec) >= 0x44 else None


def parse(rec):
    ver = rec[0]
    table = struct.unpack_from('<8h', rec, 0x44 if ver == 1 and len(rec) >= 0x54 else 0x04)
    return {
        'version': ver,
        'scales': table,
        'body': rec[0x25],
        'pick': rec[0x1c],
        'flyer': 1 if rec[0x31] & 0x80 else 0,
    }


def collect(install):
    chara = os.path.join(install, 'client', 'chara')
    out = {}
    for folder, prefix, offset in KINDS:
        root = os.path.join(chara, folder)
        if not os.path.isdir(root):
            continue
        for name in sorted(os.listdir(root)):
            if not name.startswith(prefix) or not name[1:].isdigit():
                continue
            path = os.path.join(root, name, 'skl', '0001')
            if not os.path.isfile(path):
                continue
            rec = cibb(path)
            if rec is None:
                continue
            row = parse(rec)
            row['name'] = f'{folder}/{name}'
            out[offset + int(name[1:])] = row
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--install', default=INSTALL)
    ap.add_argument('--out', default=OUT)
    args = ap.parse_args()

    rows = collect(args.install)
    if not rows:
        raise SystemExit(f'no cibb records under {args.install}')
    cols = ['modelId'] + [f'scale{i}' for i in range(8)] + ['bodyRadius', 'pickRadius', 'flyer']
    lines = [
        '-- Generated by Tools/seed/build_model_size_seed.py from each model\'s client cibb record.',
        '-- Do not edit by hand; rerun the script. Scales are /1000, radii are x0.1 (before scale).',
        'DROP TABLE IF EXISTS `gamedata_model_size`;',
        'CREATE TABLE `gamedata_model_size` (',
        '  `modelId` int(10) unsigned NOT NULL,',
    ]
    lines += [f'  `scale{i}` smallint(6) NOT NULL,' for i in range(8)]
    lines += [
        '  `bodyRadius` tinyint(3) unsigned NOT NULL,',
        '  `pickRadius` tinyint(3) unsigned NOT NULL,',
        '  `flyer` tinyint(1) unsigned NOT NULL,',
        '  PRIMARY KEY (`modelId`)',
        ') ENGINE=InnoDB DEFAULT CHARSET=latin1;',
        'INSERT INTO `gamedata_model_size` (' + ', '.join(f'`{c}`' for c in cols) + ') VALUES',
    ]
    values = []
    for mid in sorted(rows):
        r = rows[mid]
        v = [mid, *r['scales'], r['body'], r['pick'], r['flyer']]
        values.append('\t(' + ', '.join(str(x) for x in v) + ')')
    lines.append(',\n'.join(values) + ';')
    with open(args.out, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'{len(rows)} models -> {os.path.relpath(args.out, REPO)}')


if __name__ == '__main__':
    main()
