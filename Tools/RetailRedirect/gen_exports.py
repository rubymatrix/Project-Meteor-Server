#!/usr/bin/env python3
"""Regenerate exports.h and iphlpapi.def, the list of functions the proxy passes through.

The proxy must export every function the system iphlpapi.dll exports: other Windows DLLs
import from it, and once the proxy is loaded under that name they bind to the proxy.

    python3 gen_exports.py C:\\Windows\\SysWOW64\\iphlpapi.dll   # from a real DLL
    python3 gen_exports.py libiphlpapi.a                        # from the mingw import library
    python3 gen_exports.py names.txt                            # one name per line
    python3 gen_exports.py exports.h <more>                     # keep the current list, add more

Passing several inputs takes the union, so one list can cover several Windows versions.
An export that a given Windows lacks costs nothing: no DLL on that Windows imports it.
"""

import os
import re
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def names_from_pe(data):
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    nsec = struct.unpack_from("<H", data, pe + 6)[0]
    optsize = struct.unpack_from("<H", data, pe + 20)[0]
    opt = pe + 24
    magic = struct.unpack_from("<H", data, opt)[0]
    datadir = opt + (96 if magic == 0x10B else 112)
    export_rva = struct.unpack_from("<I", data, datadir)[0]
    sections = [struct.unpack_from("<8sIIII", data, pe + 24 + optsize + i * 40) for i in range(nsec)]

    def offset(rva):
        for _, vsize, va, rsize, raw in sections:
            if va <= rva < va + max(vsize, rsize):
                return raw + rva - va
        raise ValueError("rva %x outside sections" % rva)

    exp = offset(export_rva)
    count = struct.unpack_from("<I", data, exp + 24)[0]       # NumberOfNames
    names_rva = struct.unpack_from("<I", data, exp + 32)[0]   # AddressOfNames
    names = []
    for i in range(count):
        rva = struct.unpack_from("<I", data, offset(names_rva) + i * 4)[0]
        o = offset(rva)
        names.append(data[o:data.index(b"\0", o)].decode())
    return names


def names_from_mingw_lib(path):
    out = subprocess.run(["i686-w64-mingw32-nm", path], capture_output=True, text=True, check=True).stdout
    return [m.group(1) for m in re.finditer(r" I __imp__([A-Za-z0-9_]+?)(?:@\d+)?$", out, re.M)]


def read_names(path):
    if path.endswith(".a"):
        return names_from_mingw_lib(path)
    with open(path, "rb") as f:
        data = f.read()
    if data[:2] == b"MZ":
        return names_from_pe(data)
    text = data.decode()
    listed = re.findall(r"^X\(\d+, (\w+)\)", text, re.M)   # an existing exports.h
    if listed:
        return listed
    return [line.strip() for line in text.splitlines() if line.strip() and not line.startswith("#")]


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    names = sorted({n for path in sys.argv[1:] for n in read_names(path)})

    with open(os.path.join(HERE, "exports.h"), "w", newline="\n") as f:
        f.write("// Generated by gen_exports.py: every export of the system iphlpapi.dll.\n")
        f.write("// X(index, name)\n")
        for i, name in enumerate(names):
            f.write("X(%d, %s)\n" % (i, name))

    with open(os.path.join(HERE, "iphlpapi.def"), "w", newline="\n") as f:
        f.write("; Generated by gen_exports.py\nLIBRARY iphlpapi\nEXPORTS\n")
        for name in names:
            f.write("    %s=Thunk_%s\n" % (name, name))

    print("%d exports" % len(names))


if __name__ == "__main__":
    main()
